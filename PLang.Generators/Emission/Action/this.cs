using System.Linq;
using System.Text;
using PLang.Generators.Discovery;
using PLang.Generators.Emission.Property;
using DataProperty = PLang.Generators.Emission.Property.Data.@this;
using CodeProperty = PLang.Generators.Emission.Property.Code.@this;

namespace PLang.Generators.Emission.Action;

/// <summary>
/// Per-handler emission. A handler instance is the per-execution home, built fresh
/// for every action run:
///   Resolve(action, context) — validates, decodes each .pr parameter into a local,
///     constructs a fresh instance via the object initializer (init auto-props), then
///     Attach()es runtime markers. Returns the ready handler (or a resolution error).
///   Attach(action, context)  — sets Context / Action / Step / Static / Channel / [Code]
///     provider on THIS instance. Called by Resolve, and directly on prebound
///     (inline C#-composed) handlers whose params are already set.
///   Execute()                — runs the handler's typed Run(), wrapping bare exceptions
///     with the action's module.action context.
///
/// Emission uses C# raw string literals (`$$"""..."""`). With `$$`, single `{` `}`
/// are literal and `{{name}}` is interpolation.
/// </summary>
public static class @this
{
    public static string Emit(ActionClassInfo info)
    {
        var sb = new StringBuilder();

        sb.Append($$"""
            // <auto-generated/>
            #nullable enable

            using System;
            using System.Collections.Generic;
            using System.Linq;
            using System.Text.RegularExpressions;

            namespace {{info.Namespace}};

            partial class {{info.ClassName}}(global::app.actor.context.@this __ctx) : global::app.module.ICodeGenerated, global::app.module.IClass
            {

            """);

        EmitMarkers(sb, info);
        EmitInstanceState(sb);
        EmitProperties(sb, info);
        EmitRawArgsCtor(sb, info);
        EmitDataAndErrorHelpers(sb, info);
        EmitResolve(sb, info);
        EmitAttach(sb, info);
        EmitLive(sb, info);
        EmitParse(sb, info);
        EmitCheck(sb, info);
        EmitExecute(sb);
        EmitHelpers(sb);
        EmitSnapshotPublic(sb);
        EmitSnapshotInternal(sb, info);

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitMarkers(StringBuilder sb, ActionClassInfo info)
    {
        // Context is universal — every action runs inside one, and any value the handler
        // produces borns with it (Data() -> Context.Ok). Emitted unconditionally.
        sb.Append("""
                public global::app.actor.context.@this Context { get; set; } = __ctx;

            """);
        if (info.ImplementsIChannel)
            sb.Append("""
                    public global::app.channel.@this Channel { get; set; } = null!;

                """);
        if (info.ImplementsIAction)
            sb.Append("""
                    public global::app.goal.step.action.@this Action { get; set; } = null!;

                """);
        if (info.ImplementsIStep)
            sb.Append("""
                    public global::app.goal.step.@this Step { get; set; } = null!;

                """);
        if (info.ImplementsIStatic)
            sb.Append("""
                    public System.Collections.Concurrent.ConcurrentDictionary<string, object?> Static { get; set; } = null!;

                """);
    }

    private static void EmitInstanceState(StringBuilder sb)
    {
        // The action is held only so __SnapshotParams can read the .pr-side values on
        // the failure path. Set in Attach.
        sb.Append("""
                private global::app.goal.step.action.@this? __action;

            """);
    }

    private static void EmitProperties(StringBuilder sb, ActionClassInfo info)
    {
        foreach (var prop in info.Properties)
            prop.EmitProperty(sb);
    }

    /// <summary>
    /// A C#-composition ctor: params as raw, typed, named optional args wrapped with __ctx
    /// (born-with-context). Required = non-nullable + no [Default] (compiler forces it); the rest
    /// are optional and resolve through the seam (setting → [Default]) when omitted. Required args
    /// come first (C# requires non-default params before defaulted). Skipped when there are no
    /// params (the primary ctor already covers `new X(context)`).
    /// </summary>
    private static void EmitRawArgsCtor(StringBuilder sb, ActionClassInfo info)
    {
        var props = info.Properties.OfType<DataProperty>().ToList();
        if (props.Count == 0) return;

        var ordered = props.Where(p => p.CtorRequired).Concat(props.Where(p => !p.CtorRequired)).ToList();
        var sig = string.Join(", ", ordered.Select(p => p.CtorSignature));
        sb.AppendLine($"        /// <summary>C#-composition ctor — provide params as named args; omitted ones resolve via the seam.</summary>");
        sb.AppendLine($"        public {info.ClassName}(global::app.actor.context.@this __ctx, {sig}) : this(__ctx)");
        sb.AppendLine("        {");
        foreach (var p in ordered)
            sb.AppendLine($"            {p.CtorAssign}");
        sb.AppendLine("        }");
        sb.AppendLine();
    }

    private static void EmitDataAndErrorHelpers(StringBuilder sb, ActionClassInfo info)
    {
        // A handler that produces a value borns it with its own Context (context-never-null).
        var hasDataProp = info.Properties.Any(p => p.Name == "Data");
        if (!hasDataProp)
        {
            sb.Append("""
                    protected global::app.data.@this Data() => Context.Ok();
                    protected global::app.data.@this Data(object? value) => Context.Ok(value);
                    protected global::app.data.@this Data(object? value, global::app.type.@this? type) => Context.Ok(value, type);

                """);
        }
        var hasErrorProp = info.Properties.Any(p => p.Name == "Error");
        if (!hasErrorProp)
        {
            sb.Append("""
                    protected global::app.data.@this Error(global::app.error.Error error) => Context.Error(error);

                """);
        }
        sb.AppendLine();
    }

    private static void EmitResolve(StringBuilder sb, ActionClassInfo info)
    {
        sb.Append("""
                public async System.Threading.Tasks.Task<(global::app.module.ICodeGenerated?, global::app.error.Error?)> Resolve(
                    global::app.goal.step.action.@this action, global::app.actor.context.@this context)
                {
                    var app = context.App!;
                    var __step = action?.Step;
                    var __callFrames = context.CallStack?.Current?.SnapshotChain() ?? (System.Collections.Generic.IReadOnlyList<global::app.callstack.call.@this>)System.Array.Empty<global::app.callstack.call.@this>();

            """);

        // Seed = a C#-composed action (app.RunAction). Its SET params pass through Resolve
        // untouched (no round-trip); UNSET params resolve from bag → setting → [Default].
        // Declared first so the required-param validations can see seed-provided values.
        sb.AppendLine($"        var __seed = action?.Seed as {info.ClassName};");
        sb.AppendLine();

        // [IsNotNull] validation
        if (info.HasAnyIsNotNull)
        {
            sb.AppendLine("        if (action != null)");
            sb.AppendLine("        {");
            foreach (var name in info.IsNotNullProperties)
            {
                var lower = name.ToLowerInvariant();
                sb.Append($$"""
                                if (__seed?.{{name}} is not { IsInitialized: true } &&
                                    (action["{{lower}}"]?.Value?.IsNull ?? true))
                                    return (null, new global::app.error.ServiceError(
                                        "'{{lower}}' must have a value", __step, __callFrames, "ValueRequired", 400));

                    """);
            }
            sb.AppendLine("        }");
        }

        // Missing-required-parameter validation for name slots (Data<variable>, non-nullable).
        var nameProps = info.Properties
            .OfType<DataProperty>()
            .Where(p => p.IsName && !p.IsNullable)
            .ToList();
        if (nameProps.Count > 0)
        {
            sb.AppendLine("        if (action != null)");
            sb.AppendLine("        {");
            foreach (var prop in nameProps)
            {
                var lower = prop.Name.ToLowerInvariant();
                sb.Append($$"""
                                if (__seed?.{{prop.Name}} is not { IsInitialized: true } &&
                                    action["{{lower}}"]?.Value == null)
                                    return (null, new global::app.error.ServiceError(
                                        "Required property '{{lower}}' is missing or null", __step, __callFrames, "MissingRequiredProperty", 400));

                    """);
            }
            sb.AppendLine("        }");
        }

        // Resolve each parameter into a local (decode %var%/literal in this context).
        // Setting key per param is module.action.param, read off the tree location: module = first
        // segment after "app.module.action.", action = the record/class name (== the action name).
        const string settingModulePrefix = "app.module.action.";
        var settingModule = info.Namespace.StartsWith(settingModulePrefix)
            ? info.Namespace.Substring(settingModulePrefix.Length).Split('.')[0]
            : info.Namespace;
        var settingAction = info.ClassName;
        var dataProps = info.Properties.OfType<DataProperty>().ToList();
        foreach (var prop in dataProps)
            prop.EmitResolveLocal(sb, settingModule, settingAction);

        sb.AppendLine();

        // Construct the fresh instance, binding resolved params via the object initializer.
        if (dataProps.Count == 0)
        {
            sb.AppendLine($"        var __instance = new {info.ClassName}(context);");
        }
        else
        {
            sb.AppendLine($"        var __instance = new {info.ClassName}(context)");
            sb.AppendLine("        {");
            for (int i = 0; i < dataProps.Count; i++)
            {
                var comma = i < dataProps.Count - 1 ? "," : "";
                sb.AppendLine($"            {dataProps[i].InitAssignment}{comma}");
            }
            sb.AppendLine("        };");
        }

        sb.Append("""

                    var __err = await __instance.Attach(action, context);
                    if (__err != null) return (null, __err);
                    return (__instance, null);
                }

            """);
    }

    /// <summary>
    /// The build-time literal verdict (<c>IClass.Parse</c>): each literal parameter opened through
    /// its own typed view on this bound instance, a decline collected per parameter.
    /// </summary>
    private static void EmitParse(StringBuilder sb, ActionClassInfo info)
    {
        var body = new StringBuilder();
        foreach (var prop in info.Properties)
            prop.EmitParse(body);
        EmitVerdict(sb, "Parse", body);
    }

    /// <summary>
    /// The build-time variable verdict (<c>IClass.Check</c>): each whole %variable% parameter the
    /// store knows opened through its own typed view, a decline collected per parameter.
    /// </summary>
    private static void EmitCheck(StringBuilder sb, ActionClassInfo info)
    {
        var body = new StringBuilder();
        foreach (var prop in info.Properties)
            prop.EmitCheck(body);
        EmitVerdict(sb, "Check", body);
    }

    // A verdict member: the collected declines of its per-property body, or none without awaiting.
    private static void EmitVerdict(StringBuilder sb, string member, StringBuilder body)
    {
        const string returns = "System.Threading.Tasks.Task<System.Collections.Generic.IReadOnlyList<global::app.error.Error>>";
        if (body.Length == 0)
        {
            // No slot to open, so nothing to await.
            sb.AppendLine($"    public {returns} {member}()");
            sb.AppendLine($"        => System.Threading.Tasks.Task.FromResult<System.Collections.Generic.IReadOnlyList<global::app.error.Error>>(System.Array.Empty<global::app.error.Error>());");
            sb.AppendLine();
            return;
        }
        sb.AppendLine($"    public async {returns} {member}()");
        sb.AppendLine("    {");
        sb.AppendLine("        var __declined = new System.Collections.Generic.List<global::app.error.Error>();");
        sb.Append(body);
        sb.AppendLine("        return __declined;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitAttach(StringBuilder sb, ActionClassInfo info)
    {
        sb.Append("""
                public async System.Threading.Tasks.Task<global::app.error.Error?> Attach(
                    global::app.goal.step.action.@this? action, global::app.actor.context.@this context)
                {
                    var app = context.App!;
                    __action = action;
                    var __step = action?.Step;
                    var __callFrames = context.CallStack?.Current?.SnapshotChain() ?? (System.Collections.Generic.IReadOnlyList<global::app.callstack.call.@this>)System.Array.Empty<global::app.callstack.call.@this>();

            """);

        if (info.ImplementsIAction) sb.AppendLine("        Action = action!;");
        if (info.ImplementsIStep) sb.AppendLine("        Step = action?.Step!;");
        if (info.ImplementsIStatic)
        {
            const string prefix = "app.module.action.";
            var moduleName = info.Namespace.StartsWith(prefix)
                ? info.Namespace.Substring(prefix.Length).Split('.')[0]
                : info.Namespace;
            sb.AppendLine($"        Static = context.GetModuleStatic(\"{moduleName}\");");
        }

        // [Code] providers — the app's, registered when it starts
        foreach (var prop in info.Properties.OfType<CodeProperty>())
            prop.EmitAttach(sb);

        sb.Append("""
                    await System.Threading.Tasks.Task.CompletedTask;
                    return null;
                }

            """);
    }

    /// <summary>
    /// What the handler finds only when it runs — the channel it writes to, which a step may register
    /// while the app runs. Bind, which the build uses, looks it up not; <c>Execute</c> does it first, and
    /// a missing one fails the run as it always did.
    /// </summary>
    private static void EmitLive(StringBuilder sb, ActionClassInfo info)
    {
        sb.Append("""
                private async System.Threading.Tasks.Task<global::app.error.Error?> __Live()
                {
                    var context = Context;
                    var action = __action;
                    var app = context.App!;
                    var __step = action?.Step;
                    var __callFrames = context.CallStack?.Current?.SnapshotChain() ?? (System.Collections.Generic.IReadOnlyList<global::app.callstack.call.@this>)System.Array.Empty<global::app.callstack.call.@this>();

            """);
        if (info.ImplementsIChannel)
        {
            sb.Append("""
                        {
                            // The channel name is the PARSED value's string face — await Value(), not
                            // Peek(): Peek() hands back the lazy source's RAW wire slice, which for a
                            // .pr text param is the JSON-quoted form (`"builder"`) and misses the
                            // channel registered under the clean name. Read on this run's own Data,
                            // made from the program's property.
                            var __channelParam = action?["channel"]?.Data(context);
                            var __channelName = __channelParam == null ? null : (await __channelParam.Value())?.ToString();
                            Channel = (context.Actor ?? app.User).Channel.Resolve(__channelName);
                            if (Channel == null)
                                return new global::app.error.ServiceError(
                                    $"Channel '{__channelName ?? "output"}' not found", __step, __callFrames, "ChannelNotFound", 404);
                        }

                """);
        }

        sb.Append("""
                    await System.Threading.Tasks.Task.CompletedTask;
                    return null;
                }

            """);
    }

    private static void EmitExecute(StringBuilder sb)
    {
        sb.Append("""
                public async System.Threading.Tasks.Task<global::app.data.@this> Execute()
                {
                    // what exists only at run — the channel — is found now
                    if (await __Live() is { } __missing) return global::app.data.@this.FromError(__missing);
                    try { return await Run(); }
                    catch (System.Exception ex) when (ex is not (System.OperationCanceledException or System.OutOfMemoryException or System.StackOverflowException))
                    {
                        // Bare exceptions from Run() (NRE, InvalidCast, etc.) reach the user
                        // as "Object reference not set" with no module.action context. Wrap
                        // here so the message tells the reader which action's Run() threw.
                        var __mod = __action?.Module.Name ?? "?";
                        var __act = __action?.Name ?? "?";
                        var __step = __action?.Step;
                        var __callFrames = Context?.CallStack?.Current?.SnapshotChain() ?? (System.Collections.Generic.IReadOnlyList<global::app.callstack.call.@this>)System.Array.Empty<global::app.callstack.call.@this>();
                        // A typed AppException carries a domain Key (VariableNotFound, …) — preserve
                        // it; a bare exception falls back to its type name.
                        var __ap = ex as global::app.error.AppException;
                        return global::app.data.@this.FromError(new global::app.error.ServiceError(
                            $"{__mod}.{__act}: {ex.GetType().Name}: {ex.Message}",
                            __step!, __callFrames, __ap?.Key ?? ex.GetType().Name, __ap?.StatusCode ?? 500)
                        { Exception = ex });
                    }
                }

            """);
    }

    private static void EmitHelpers(StringBuilder sb)
    {
        sb.Append("""
                // The program holds properties, shared by every run — a run makes its own first Data
                // from one, born with the running context. A plain slot takes the step's property,
                // then the frozen default; a typed slot asks the step's (__View) and the frozen
                // default (__Default, action.Default's) separately, so a setting can sit between them.
                private static global::app.data.@this __Copy(
                    global::app.goal.step.action.@this? action, string name, global::app.actor.context.@this context)
                    => (action?[name] ?? action?.Default[name])?.Data(context) ?? global::app.data.@this.NotFound(name);

                private static global::app.data.@this<T> __View<T>(
                    global::app.goal.step.action.@this? action, string name, global::app.actor.context.@this context)
                    where T : global::app.type.item.@this, global::app.type.item.ICreate<T>
                    => action?[name]?.Data(context).As<T>() ?? global::app.data.@this.NotFound(name).As<T>();

                private static global::app.data.@this<T> __Default<T>(
                    global::app.goal.step.action.@this? action, string name, global::app.actor.context.@this context)
                    where T : global::app.type.item.@this, global::app.type.item.ICreate<T>
                    => action?.Default[name]?.Data(context).As<T>() ?? global::app.data.@this.NotFound(name).As<T>();

                // Wraps a resolution error with the action's module.action context so the
                // reader can locate the failing call site. The raw error from Data<T>.As<T>
                // only carries source/target type names — useless without the action name.
                private static global::app.error.Error __PrefixActionContext(
                    global::app.error.Error err, global::app.goal.step.action.@this? action)
                {
                    if (action == null) return err;
                    var msg = $"{action.Module}.{action.Name}: {err.Message}";
                    return new global::app.error.ActionError(msg, err.Key ?? "ActionError", err.StatusCode);
                }

            """);
    }

    private static void EmitSnapshotPublic(StringBuilder sb)
    {
        // Public surface for the call-stack catch path.
        sb.Append("""
                public System.Collections.Generic.List<global::app.error.ParamSnapshot> SnapshotParams()
                    => __SnapshotParams();

            """);
    }

    private static void EmitSnapshotInternal(StringBuilder sb, ActionClassInfo info)
    {
        sb.Append("""
                private System.Collections.Generic.List<global::app.error.ParamSnapshot> __SnapshotParams()
                {
                    var __list = new System.Collections.Generic.List<global::app.error.ParamSnapshot>();
            """);
        sb.AppendLine();
        foreach (var prop in info.Properties)
            prop.EmitSnapshotEntry(sb);
        sb.Append("""
                    return __list;
                }
            """);
        sb.AppendLine();
    }
