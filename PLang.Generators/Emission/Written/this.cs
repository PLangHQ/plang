using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace PLang.Generators.Emission.Written;

/// <summary>
/// The classes an assembly's code wrote that plang's facts read, listed at compile time so a cold start reads a list
/// instead of walking every class by reflection: the item classes (types, kind classes, family subclasses), the classes
/// declaring formats ([Format]), the closed sets ([Choice]), the action classes ([Action]), the classes in a
/// <c>serializer</c> namespace (readers) and in a <c>format</c> namespace (write pairs). Each list is a superset: the
/// runtime applies its own rules to it, as it would to every class. Emitted as <c>PLang.Generated.Written</c>, only for
/// an assembly that is plang code (it references plang's item class).
/// </summary>
internal static class @this
{
    public static void Register(IncrementalGeneratorInitializationContext context)
        => context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) =>
        {
            if (Emit(compilation) is { } source) spc.AddSource("PLang.Generated.Written.g.cs", source);
        });

    private static string? Emit(Compilation compilation)
    {
        var item = compilation.GetTypeByMetadataName("app.type.item.this");
        if (item is null) return null;
        var format = compilation.GetTypeByMetadataName("app.Attributes.FormatAttribute");
        var choice = compilation.GetTypeByMetadataName("app.Attributes.ChoiceAttribute");
        var action = compilation.GetTypeByMetadataName("app.module.ActionAttribute");

        var items = new List<string>();
        var formats = new List<string>();
        var choices = new List<string>();
        var actions = new List<string>();
        var serializers = new List<string>();
        var pairs = new List<string>();
        foreach (var type in Types(compilation.Assembly.GlobalNamespace))
        {
            if (!Reachable(type) || Of(type) is not { } name) continue;
            if (Derives(type, item)) items.Add(name);
            if (Declares(type, format)) formats.Add(name);
            if (Declares(type, choice)) choices.Add(name);
            if (Declares(type, action)) actions.Add(name);
            var space = type.ContainingNamespace?.ToDisplayString() ?? "";
            if (space.EndsWith(".serializer")) serializers.Add(name);
            if (space.EndsWith(".format")) pairs.Add(name);
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("namespace PLang.Generated;");
        sb.AppendLine();
        sb.AppendLine("internal static class Written");
        sb.AppendLine("{");
        List(sb, "Item", items);
        List(sb, "Format", formats);
        List(sb, "Choice", choices);
        List(sb, "Action", actions);
        List(sb, "Serializer", serializers);
        List(sb, "Pair", pairs);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void List(StringBuilder sb, string name, List<string> types)
    {
        sb.AppendLine($"    internal static readonly global::System.Type[] {name} = new global::System.Type[]");
        sb.AppendLine("    {");
        foreach (var type in types) sb.AppendLine($"        typeof({type}),");
        sb.AppendLine("    };");
    }

    // Every class, struct and enum the assembly's source declares, nested ones included.
    private static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol space)
    {
        foreach (var member in space.GetMembers())
            if (member is INamespaceSymbol inner)
                foreach (var type in Types(inner)) yield return type;
            else if (member is INamedTypeSymbol type)
                foreach (var each in Nested(type)) yield return each;
    }

    private static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol type)
    {
        yield return type;
        foreach (var inner in type.GetTypeMembers())
            foreach (var each in Nested(inner)) yield return each;
    }

    // A class the generated list can name: neither it nor a class holding it is private or protected, and no class
    // holding it is generic (typeof can't name an open nested class).
    private static bool Reachable(INamedTypeSymbol type)
    {
        for (var at = type; at != null; at = at.ContainingType)
        {
            if (at.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal) return false;
            if (!SymbolEqualityComparer.Default.Equals(at, type) && at.IsGenericType) return false;
        }
        return true;
    }

    // The class as typeof names it: fully qualified, a generic definition open (list.@this<>).
    private static string? Of(INamedTypeSymbol type)
    {
        var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat
            .WithGenericsOptions(SymbolDisplayGenericsOptions.None));
        return type.Arity == 0 ? name : name + "<" + new string(',', type.Arity - 1) + ">";
    }

    private static bool Derives(INamedTypeSymbol type, INamedTypeSymbol @base)
    {
        for (var at = type.BaseType; at != null; at = at.BaseType)
            if (SymbolEqualityComparer.Default.Equals(at.OriginalDefinition, @base)) return true;
        return SymbolEqualityComparer.Default.Equals(type, @base);
    }

    private static bool Declares(INamedTypeSymbol type, INamedTypeSymbol? attribute)
        => attribute != null && type.GetAttributes().Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, attribute));
}
